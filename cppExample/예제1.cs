public class 예제1
{
    public static void Main()
    {
        //1. `printf` 사용: 본인 이름, 전화번호, 이메일 출력 프로그램 작성.
        Console.WriteLine("이승연, 000-0000-0000, email: leelaf@naver.com");

        //2. `printf` 사용: 두 정수의 사칙연산(덧셈, 뺄셈, 곱셈, 나눗셈) 결과 출력 프로그램 작성. (나눗셈: 실수 결과 출력)
        {
            int a = 10;
            int b = 20;
            Console.WriteLine($"덧셈:{a + b}, 뺄셈:{a - b}, 곱셈:{a * b}, 나눗셈:{a / b}");
        }

        //3. **정수 오른쪽 정렬 출력**: 숫자 `123`을 총 5칸을 확보하여 오른쪽으로 정렬하여 출력해보세요. (빈칸은 공백으로 채움)
        //    - 예상 출력:

        //    ```
        //      123
        //    ```
        {
            int a = 123;

            Console.WriteLine($"{a,5:N0}");
        }

        //4. **정수 오른쪽 정렬 및 0 채우기 출력**: 숫자 `45`를 총 5칸을 확보하여 오른쪽으로 정렬하고, 빈칸은 `0`으로 채워서 출력해보세요.
        //    - 예상 출력:

        //    ```
        //    00045
        //    ```
        {
            int a=45;
            Console.WriteLine($"{a:D5}");
        }

        //5. **실수 소수점 자릿수 지정 출력**: 숫자 `123.456789`를 소수점 이하 3자리까지만 출력해보세요. (반올림 적용)
        //    - 예상 출력:

        //    ```
        //    123.457
        //    ```
        {
            double a=123.456789;
            Console.WriteLine($"{a:0.000}");
        }
        //6. **문자열 일부 출력**: 문자열 "Hello World"에서 앞의 5글자만 출력해보세요.
        //    - 예상 출력:

        //    ```
        //    Hello
        //    ```
        {
            string a = "Hello World";
            Console.WriteLine($"{a.Substring(0, 5)}");
        }

        //7. **여러 값 조합하여 문장 출력**: 다음과 같은 문장을 `printf`를 한 번만 사용하여 출력해보세요.
        //    - "제품 ID: `A001`, 가격: `15000`원, 수량: `3`개"
        //    - 예상 출력:
        {
            String Id = "A001";
            int cost = 15000;
            int capacity = 3;
            Console.WriteLine($"제품 ID:'{Id}', 가격:'{cost}'원, 수량:'{capacity}'개");
        }
    }
}
